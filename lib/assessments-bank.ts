const BLOCK_ORDER: AssessSection[] = ["classroom", "home", "weekly-a", "weekly-b", "weekly-c"];

export function assessmentsForLesson(lessonId: string): AssessQuestion[] {
  return BANK.filter((row) => row.lessonId === lessonId);
}

export function assessBlocksForLesson(lessonId: string): AssessBlock[] {
  const rows = assessmentsForLesson(lessonId);
  const seen = new Set<string>();
  const blocks: AssessBlock[] = [];
  for (const row of rows) {
    const key = `${row.period}-${row.section}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const group = rows.filter((item) => item.period === row.period && item.section === row.section);
    blocks.push({
      key,
      titleAr: SECTION_TITLE[row.section],
      titleEn: SECTION_TITLE_EN[row.section],
      period: row.period,
      section: row.section,
      essays: group.filter((item) => item.kind === "essay"),
      mcq: group.filter((item) => item.kind === "mcq"),
    });
  }
  return blocks.sort((left, right) => {
    if (left.period !== right.period) return left.period - right.period;
    return BLOCK_ORDER.indexOf(left.section) - BLOCK_ORDER.indexOf(right.section);
  });
}

